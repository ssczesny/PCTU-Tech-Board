#!/usr/bin/env python3
"""Assemble post-mortem.html (the published artifact page) from src/.

    python3 build.py            # writes post-mortem.html
    python3 build.py out.html   # writes elsewhere (tests)

The page is one self-contained file: head + <style> + body + one <script>. Data files are inlined.
"""
import glob, json, os, sys
ROOT = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(ROOT, 'src')
rd = lambda *p: open(os.path.join(SRC, *p), encoding='utf8').read()
js = ''.join(rd('js', os.path.basename(f)).rstrip('\n') + '\n\n' for f in sorted(glob.glob(os.path.join(SRC, 'js', '*.js'))))
puzzles = json.loads(rd('data', 'puzzles.json')); lessons = json.loads(rd('data', 'lessons.json'))
pgn = rd('data', 'example.pgn').strip()
data = ('/* ================= data (generated by build.py from src/data) ================= */\n'
        + 'const EXAMPLE_PGN = ' + json.dumps(pgn, ensure_ascii=False) + ';\n'
        + 'const PUZZLES = ' + json.dumps(puzzles, separators=(',', ':'), ensure_ascii=False) + ';\n'
        + 'const LESSONS = ' + json.dumps(lessons, separators=(',', ':'), ensure_ascii=False) + ';\n\n')
js = data + js
assert '</script' not in js.lower(), 'script-closing text inside the script'
out = (rd('head.html').rstrip('\n') + '\n<style>\n' + rd('styles.css').rstrip('\n') + '\n\n' + rd('pieces.css').rstrip('\n') + '\n</style>\n\n'
       + rd('body.html').rstrip('\n') + '\n\n<script src="https://cdnjs.cloudflare.com/ajax/libs/chess.js/0.10.3/chess.min.js"></script>\n<script>\n(() => {\n\'use strict\';\n\n'
       + js.rstrip('\n') + '\n})();\n</script>\n')
dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'post-mortem.html')
open(dest, 'w', encoding='utf8').write(out)
print('built %s: %d bytes, %d puzzles, %d lessons' % (os.path.basename(dest), len(out.encode('utf8')), len(puzzles), len(lessons)))
